"""Generate optional OS Evolution registry/header from its canonical contract."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'contracts/EVOLUTION-v1.json'
PACKAGED = ROOT / 'fire_backend/data/EVOLUTION-v1.json'
HEADER = ROOT.parent / 'M5Stack-device/src/fire_evolution_contract.h'


def generated(document):
    registry = document['registry']
    payload = json.dumps(registry, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()
    digest = hashlib.sha256(payload).hexdigest()
    if digest != document['api_contract']:
        raise ValueError('Evolution canonical contract checksum is stale')
    lines = ['// Generated by scripts/build_evolution_contract.py; DO NOT EDIT.',
             '#pragma once', '#include <cstdint>', 'namespace FireEvolutionContract {',
             f'inline constexpr char kVersion[] = "{registry["api_version"]}";',
             f'inline constexpr char kContract[] = "{digest}";']
    for key, value in registry['limits'].items():
        if type(value) is not int or not 0 < value <= 0xffffffff:
            raise ValueError('Invalid native Evolution limit')
        name = 'k' + ''.join(part.capitalize() for part in key.split('_'))
        lines.append(f'inline constexpr uint32_t {name} = {value};')
    return ('\n'.join([*lines, '} // namespace FireEvolutionContract', ''])).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = SOURCE.read_bytes()
    header = generated(json.loads(raw))
    if args.check:
        if PACKAGED.read_bytes() != raw or HEADER.read_bytes() != header:
            raise SystemExit('Evolution packaged/native contract is stale')
    else:
        PACKAGED.write_bytes(raw)
        HEADER.write_bytes(header)
    print('Evolution canonical, packaged registry and native constants match')


if __name__ == '__main__':
    main()
