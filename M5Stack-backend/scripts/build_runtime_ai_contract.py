"""Generate the optional Runtime AI contract data and native constants.

The extension never changes the existing hardware or App SDK contracts.
Use --check in validation to reject stale packaged data or native constants.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "contracts/RUNTIME_AI-v1.json"
PACKAGED = ROOT / "fire_backend/data/RUNTIME_AI-v1.json"
HEADER = ROOT.parent / "M5Stack-device/src/fire_runtime_ai_contract.h"


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


def generated_header(document):
    registry = document["registry"]
    digest = hashlib.sha256(canonical(registry)).hexdigest()
    if digest != document["api_contract"]:
        raise ValueError("Runtime AI contract hash is stale")
    constants = {
        "kInstructionsBytes": "instructions_bytes",
        "kDataBytes": "data_bytes",
        "kSchemaBytes": "schema_bytes",
        "kRequestBytes": "request_bytes",
        "kResultBytes": "result_bytes",
        "kTimeoutDefaultMs": "timeout_default_ms",
        "kTimeoutMinMs": "timeout_min_ms",
        "kTimeoutMaxMs": "timeout_max_ms",
        "kPendingPerApp": "pending_per_app",
        "kJsonDepth": "json_depth",
        "kJsonObjectKeys": "json_object_keys",
        "kJsonArrayItems": "json_array_items",
        "kJsonStringBytes": "json_string_bytes",
    }
    lines = [
        "// Generated by M5Stack-backend/scripts/build_runtime_ai_contract.py; DO NOT EDIT.",
        "#pragma once", "#include <cstdint>", "namespace FireRuntimeAiContract {",
        f'inline constexpr char kVersion[] = "{registry["api_version"]}";',
        f'inline constexpr char kContract[] = "{digest}";',
    ]
    lines += [f"inline constexpr uint32_t {name} = {registry['limits'][key]};" for name, key in constants.items()]
    return ("\n".join(lines + ["} // namespace FireRuntimeAiContract", ""])).encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = CONTRACT.read_bytes()
    header = generated_header(json.loads(data))
    if args.check:
        if not PACKAGED.is_file() or PACKAGED.read_bytes() != data or not HEADER.is_file() or HEADER.read_bytes() != header:
            raise SystemExit("Runtime AI generated data is stale; run scripts/build_runtime_ai_contract.py")
        print("Runtime AI contract, packaged data and native constants match")
    else:
        PACKAGED.write_bytes(data)
        HEADER.write_bytes(header)
        print("Generated optional Runtime AI packaged data and native constants")


if __name__ == "__main__":
    main()
