"""Generate one small OS-only app-icon selector from the backend's shared rules."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'fire_backend/data/app_icons.json'
HEADER = ROOT.parent / 'M5Stack-device/src/fire_app_icons.h'


def generate():
    rules = json.loads(DATA.read_text(encoding='utf-8'))
    assets = {a['id'] for a in json.loads((ROOT/'fire_backend/data/app_sdk/assets.json').read_text())['assets']}
    ids = list(dict.fromkeys([rules['fallback'], *(r['icon'] for r in rules['rules'])]))
    assert set(ids) <= assets
    lines = ['// Generated by M5Stack-backend/scripts/build_app_icons.py. OS metadata only.',
             '#pragma once', '#include <cstddef>', '#include <cstring>', 'namespace fire_app_icons {',
             'inline constexpr const char* ids[] = {' + ','.join(json.dumps(i) for i in ids) + '};',
             'inline bool valid(const char* id) { if (!id) return false; for (const char* v:ids) if (!std::strcmp(v,id)) return true; return false; }',
             'inline void normalise(const char* input, char (&out)[256]) {',
             '  unsigned n=0; bool space=false; if (!input) {out[0]=0;return;}',
             '  const auto put=[&](char c) {if (n<255) out[n++]=c;};',
             '  for (unsigned i=0;input[i] && i<1024 && n<255;++i) {',
             '    unsigned char c=static_cast<unsigned char>(input[i]); const char* folded=nullptr;',
             '    if (c==0xc3 && input[i+1]) {',
             '      const unsigned char d=static_cast<unsigned char>(input[i+1]);',
             '      if (d==0xa6 || d==0x86) folded="ae"; else if (d==0xb8 || d==0x98) folded="o"; else if (d==0xa5 || d==0x85) folded="a";',
             '      if (folded) ++i;',
             '    }',
             '    if (c>=\'A\' && c<=\'Z\') c+=\'a\'-\'A\';',
             '    if (folded || (c>=\'a\' && c<=\'z\') || (c>=\'0\' && c<=\'9\')) {',
             '      if (space && n) put(\' \'); space=false;',
             '      if (folded) {for (unsigned k=0;folded[k];++k) put(folded[k]);} else put(static_cast<char>(c));',
             '    } else space=true;',
             '  } out[n]=0;',
             '}',
             'inline bool startsWord(const char* text,const char* word) {',
             '  const char* found=text;while ((found=std::strstr(found,word))) {if (found==text || found[-1]==\' \') return true; ++found;} return false;',
             '}',
             'inline const char* select(const char* name,const char* declared=nullptr) {',
             '  if (declared) for (const char* id:ids) if (!std::strcmp(id,declared)) return id;',
             '  char text[256];normalise(name,text);']
    for rule in rules['rules']:
        assert all(w and w.isascii() and len(w)<40 for w in rule['keywords'])
        condition = ' || '.join('startsWord(text,'+json.dumps(w)+')' for w in rule['keywords'])
        lines.append('  if ('+condition+') return '+json.dumps(rule['icon'])+';')
    lines += ['  return '+json.dumps(rules['fallback'])+';', '}', '} // namespace fire_app_icons', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    text=generate()
    if args.check:
        if HEADER.read_text(encoding='utf-8')!=text:raise SystemExit('App icon selector is stale')
    else:HEADER.write_text(text,encoding='utf-8',newline='\n')
