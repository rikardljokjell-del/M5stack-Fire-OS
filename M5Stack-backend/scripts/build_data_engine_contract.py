"""Generate the optional Data Engine's packaged registry and native constants."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / 'contracts/DATA_ENGINE-v1.json'
PACKAGED = ROOT / 'fire_backend/data/DATA_ENGINE-v1.json'
HEADER = ROOT.parent / 'M5Stack-device/src/fire_data_engine_contract.h'


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')


def generated_header(document):
    registry = document['registry']
    digest = hashlib.sha256(canonical(registry)).hexdigest()
    if digest != document['api_contract']:
        raise ValueError('Data Engine contract hash is stale')
    lines = ['// Generated by scripts/build_data_engine_contract.py; DO NOT EDIT.',
             '#pragma once', '#include <cstdint>', 'namespace FireDataEngineContract {',
             f'inline constexpr char kVersion[] = "{registry["api_version"]}";',
             f'inline constexpr char kContract[] = "{digest}";']
    for key, value in registry['limits'].items():
        if type(value) is not int or value < 1 or value > 0xffffffff:
            raise ValueError('Invalid native Data Engine limit')
        name = 'k' + ''.join(part[0].upper() + part[1:] for part in key.split('_'))
        lines.append(f'inline constexpr uint32_t {name} = {value};')
    lines.extend(['} // namespace FireDataEngineContract', ''])
    return '\n'.join(lines).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = CONTRACT.read_bytes()
    header = generated_header(json.loads(raw))
    if args.check:
        if not PACKAGED.exists() or PACKAGED.read_bytes() != raw or not HEADER.exists() or HEADER.read_bytes() != header:
            raise SystemExit('Data Engine packaged/native registry is stale')
        print('Data Engine canonical, packaged data and native constants match')
    else:
        PACKAGED.write_bytes(raw)
        HEADER.write_bytes(header)
        print('Generated optional Data Engine packaged data and native constants')


if __name__ == '__main__':
    main()
