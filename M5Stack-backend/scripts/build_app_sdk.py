"""Generate the native flash-only SDK header from the canonical backend data.

No network, firmware build, device I/O, private keys or external art tool is used.
--check makes CI reject stale native data without modifying any file.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "fire_backend/data/app_sdk"
HEADER = ROOT.parent / "M5Stack-device/src/fire_app_sdk_data.h"


def canonical(value):
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode()


def generate():
    sdk = json.loads((DATA / "sdk.json").read_text(encoding="utf8"))
    assets = json.loads((DATA / "assets.json").read_text(encoding="utf8"))["assets"]
    fonts = json.loads((DATA / "fonts.json").read_text(encoding="utf8"))["fonts"]
    contract = json.loads((ROOT / "contracts/APP_SDK-v1.json").read_text(encoding="utf8"))
    assert contract["api_contract"] == hashlib.sha256(canonical(contract["registry"])).hexdigest()
    lines = ["// Generated by M5Stack-backend/scripts/build_app_sdk.py; DO NOT EDIT.",
             "// Third-party attribution: M5Stack-backend/fire_backend/data/app_sdk/licenses/.",
             "#pragma once", "#include <cstdint>", "#include <cstddef>", "namespace FireSdkData {",
             "struct Asset { const char* id; uint16_t width,height; const uint16_t* palette; uint16_t paletteSize; const uint8_t* runs; uint32_t runBytes; bool tintable; };",
             "struct Glyph { uint32_t codepoint; uint8_t width,height,advance; int8_t xOffset,yOffset; const uint32_t* rows; };",
             "struct Font { const char* id; uint8_t lineHeight,ascent,descent; const Glyph* glyphs; uint16_t glyphCount; };",
             'inline constexpr char kVersion[] = ' + json.dumps(sdk["version"]) + ";",
             'inline constexpr char kContract[] = ' + json.dumps(contract["api_contract"]) + ";",
             'inline constexpr uint32_t kUpdateCallbackMs = ' + str(contract["registry"]["budgets"]["sdk_update_callback_ms"]) + ";"]
    asset_rows = []
    seen = set()
    for i, item in enumerate(sorted(assets, key=lambda a: a["id"])):
        assert item["id"] not in seen and item["id"].isascii()
        seen.add(item["id"])
        w, h, palette = item["width"], item["height"], item["palette"]
        runs = base64.b64decode(item["runs_b64"], validate=True)
        assert 1 <= w <= 64 and 1 <= h <= 64 and 1 <= len(palette) <= 256
        assert len(runs) % 2 == 0 and sum(runs[::2]) == w * h
        assert all(1 <= n <= 255 for n in runs[::2]) and all(n < len(palette) for n in runs[1::2])
        assert all(type(c) is int and 0 <= c <= 65535 for c in palette)
        lines.append(f"inline constexpr uint16_t assetPalette{i}[] = {{" + ",".join(map(str, palette)) + "};")
        lines.append(f"inline constexpr uint8_t assetRuns{i}[] = {{" + ",".join(map(str, runs)) + "};")
        asset_rows.append("{" + json.dumps(item["id"]) + f",{w},{h},assetPalette{i},{len(palette)},assetRuns{i},{len(runs)}," + str(item["tintable"]).lower() + "}")
    lines += ["inline constexpr Asset kAssets[] = {" + ",\n".join(asset_rows) + "};",
              "inline constexpr size_t kAssetCount = sizeof(kAssets)/sizeof(kAssets[0]);"]
    font_rows = []
    for i, (name, font) in enumerate(sorted(fonts.items())):
        glyph_rows = []
        for j, (cp, g) in enumerate(sorted(font["glyphs"].items(), key=lambda p: int(p[0]))):
            w, h = g["width"], g["height"]
            assert 0 <= w <= 32 and 0 <= h <= 32 and len(g["rows"]) == h
            assert 0 <= g["advance"] <= 255 and -128 <= g["x_offset"] <= 127 and -128 <= g["y_offset"] <= 127
            assert all(type(row) is int and 0 <= row < 1 << w for row in g["rows"])
            lines.append(f"inline constexpr uint32_t fontRows{i}_{j}[] = {{" + ",".join(map(str, g["rows"] or [0])) + "};")
            glyph_rows.append(f"{{{int(cp)},{w},{h},{g['advance']},{g['x_offset']},{g['y_offset']},fontRows{i}_{j}}}")
        lines.append(f"inline constexpr Glyph fontGlyphs{i}[] = {{" + ",".join(glyph_rows) + "};")
        font_rows.append("{" + json.dumps(name) + f",{font['line_height']},{font['ascent']},{font['descent']},fontGlyphs{i},{len(glyph_rows)}" + "}")
    lines += ["inline constexpr Font kFonts[] = {" + ",".join(font_rows) + "};",
              "inline constexpr size_t kFontCount = sizeof(kFonts)/sizeof(kFonts[0]);"]
    ui = (DATA / sdk["ui_file"]).read_text(encoding="utf8")
    assert ')FIRE_SDK_UI"' not in ui
    lines += ['inline constexpr char kUiSource[] = R"FIRE_SDK_UI(' + ui + ')FIRE_SDK_UI";', "} // namespace FireSdkData", ""]
    return "\n".join(lines).encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument("--check", action="store_true")
    args = parser.parse_args(); data = generate()
    contract_bytes = (ROOT / "contracts/APP_SDK-v1.json").read_bytes()
    packaged_contract = DATA / "contract.json"
    if args.check:
        if (not HEADER.exists() or HEADER.read_bytes() != data or
                not packaged_contract.exists() or packaged_contract.read_bytes() != contract_bytes):
            raise SystemExit("Native SDK header is stale; run scripts/build_app_sdk.py")
        print("Native SDK header matches canonical assets, fonts, UI and contract")
    else:
        packaged_contract.write_bytes(contract_bytes)
        HEADER.write_bytes(data)
        print(f"Generated native SDK header ({len(data)} source bytes, flash-only tables)")
